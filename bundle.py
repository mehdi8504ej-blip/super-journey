    n = 0
    for info in z.infolist():
        target = os.path.normpath(os.path.join(root, info.filename))
        if not target.startswith(root + os.sep):
            raise SystemExit("unsafe path in bundle: " + info.filename)
        if info.is_dir():
            os.makedirs(target, exist_ok=True)
            continue
